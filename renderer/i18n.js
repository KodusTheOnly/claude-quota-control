  const LANGUAGES = [
    { code: "en", label: "English", locale: "en-US" },
    { code: "pt-BR", label: "Português (Brasil)", locale: "pt-BR" },
  ];

  let lang = "en";

  function normalize(code) {
    return LANGUAGES.some((l) => l.code === code) ? code : "en";
  }

  function t(key, params) {
    let text = DICT[lang][key];
    if (text === undefined) text = DICT.en[key];
    if (text === undefined) return key;
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, (m, name) => (name in params ? String(params[name]) : m));
  }

  function setLang(code) {
    lang = normalize(code);
    return lang;
  }

  function getLang() {
    return lang;
  }

  function locale() {
    return LANGUAGES.find((l) => l.code === lang).locale;
  }

  // Applies the fixed HTML text
  function applyStatic(scope) {
    const rootEl = scope || (typeof document !== "undefined" ? document : null);
    if (!rootEl) return;
    rootEl.querySelectorAll("[data-i18n]").forEach((n) => {
      n.textContent = t(n.dataset.i18n);
    });
    rootEl.querySelectorAll("[data-i18n-title]").forEach((n) => {
      n.title = t(n.dataset.i18nTitle);
    });
    rootEl.querySelectorAll("[data-i18n-aria]").forEach((n) => {
      n.setAttribute("aria-label", t(n.dataset.i18nAria));
    });
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang === "pt-BR" ? "pt-BR" : "en";
      document.title = t("app.name");
    }
  }

  const api = { t, setLang, getLang, locale, languages: LANGUAGES, applyStatic, normalize, DICT };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  else root.I18N = api;
